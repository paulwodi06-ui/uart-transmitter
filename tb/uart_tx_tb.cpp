// a small C++ programme to instantiate UART hardware 

#include "Vuart_tx.h"
#include "verilated.h"
#include "verilated_vcd_c.h"
#include <iostream>

// The following variables track simulation time and give our clock function access to the waveform recorder 
vluint64_t sim_time = 0;
VerilatedVcdC* waveform = nullptr;

void clock_cycle(Vuart_tx& uart) {
    uart.clk = 0;
    uart.eval();

    if (waveform) {
        waveform->dump(sim_time);
    }
    sim_time += 5;

    uart.clk = 1;
    uart.eval();

    if (waveform) {
        waveform->dump(sim_time);
    }
    sim_time += 5;
}

bool test_frame(Vuart_tx& uart, int test_byte, bool reset_before = true) {

    if (reset_before) {
        uart.rst = 1;
        uart.tx_start = 0;
        clock_cycle(uart);
        uart.rst = 0;
    }

    // Request transmission
    uart.data_in = test_byte;
    uart.tx_start = 1;
    clock_cycle(uart);
    uart.tx_start = 0;

    // Enter START
    clock_cycle(uart);

    bool passed = true;

    for (int bit = 0; bit < 10; bit++) {
        int expected;

        if (bit == 0) {
            expected = 0;
        }
        else if (bit == 9) {
            expected = 1;
        }
        else {
            expected = (test_byte >> (bit - 1)) & 1;
        }

        for (int cycle = 0; cycle < 10; cycle++) {
            if (uart.tx != expected || uart.busy != 1) {
                std::cout << "Mismatch for byte " << test_byte
                          << ", frame bit " << bit
                          << ", cycle " << cycle << std::endl;
                passed = false;
            }

            clock_cycle(uart);
        }
    }

    // Check the transmitter has returned to IDLE
    if (uart.tx != 1 || uart.busy != 0) {
        passed = false;
    }

    return passed;
}

int main(int argc, char** argv) {
    Verilated::commandArgs(argc, argv);
    Verilated::traceEverOn(true);

    Vuart_tx uart; // C++ model of the SystemVerilog hardware generated by Verilator

    VerilatedVcdC vcd;
    uart.trace(&vcd, 99); // connects the hardware model to the waveform recorder
    vcd.open("uart_waveform.vcd");

    waveform = &vcd; 

    uart.clk = 0;
    uart.rst = 1;
    uart.tx_start = 0;
    uart.data_in = 0;

    uart.eval();

    // Simulate 10 clock cycles:
    for (int i = 0; i < 10; i++) {
        clock_cycle(uart);
    }

    uart.rst = 0;  // Release reset so UART operates normally 

    std::cout << "UART simulation started!" << std::endl;
    std::cout << "TX = " << (int)uart.tx << std::endl;
    std::cout << "Busy = " << (int)uart.busy << std::endl;


    // Request transmission of ASCII character 'A'
    uart.data_in = 0x41;
    uart.tx_start = 1;

    clock_cycle(uart);

    // Remove the transmission request
    uart.tx_start = 0;

    // Allow the transmitter to enter START
    clock_cycle(uart);

    std::cout << "After starting transmission:" << std::endl;
    std::cout << "TX = " << (int)uart.tx << std::endl;
    std::cout << "Busy = " << (int)uart.busy << std::endl;

    // Complete the remaining 9 cycles of the START state
    for (int i = 0; i < 9; i++) {
        clock_cycle(uart);
    }

    std::cout << "After 10 START cycles:" << std::endl;
    std::cout << "TX = " << (int)uart.tx << std::endl;
    std::cout << "Busy = " << (int)uart.busy << std::endl;

    // Advance one more clock cycle into DATA
    clock_cycle(uart);

    std::cout << "First data bit:" << std::endl;
    std::cout << "TX = " << (int)uart.tx << std::endl;

    // Check all 8 data bits
    bool all_passed = true;

    for (int bit = 0; bit < 8; bit++) {
        int expected = (0x41 >> bit) & 1;
        int actual = uart.tx;

        std::cout << "Bit " << bit
                << ": Expected = " << expected
                << ", Actual = " << actual << std::endl;

        if (actual != expected) {
            all_passed = false;
        }

        // Advance to the next data bit
        if (bit < 7) {
            for (int cycle = 0; cycle < 10; cycle++) {
                clock_cycle(uart);
            }
        }
    }

    if (all_passed) {
        std::cout << "All 8 data bits PASSED!" << std::endl;
    } else {
        std::cout << "Data bit test FAILED!" << std::endl;
    }


    int test_bytes[] = {0x00, 0xFF, 0x55, 0xAA, 0x41};

    bool all_tests_passed = all_passed;

    for (int i = 0; i < 5; i++) {
        if (test_frame(uart, test_bytes[i])) {
            std::cout << "Test " << i + 1 << " PASSED" << std::endl;
        }
        else {
            std::cout << "Test " << i + 1 << " FAILED" << std::endl;
            all_tests_passed = false;
        }
    }

    // Test consecutive transmissions without an intervening reset
    bool first_passed = test_frame(uart, 0x55, true);
    bool second_passed = test_frame(uart, 0xAA, false);

    if (first_passed && second_passed) {
        std::cout << "Consecutive transmission test PASSED!"
                << std::endl;
    }
    else {
        std::cout << "Consecutive transmission test FAILED!"
                << std::endl;
        all_tests_passed = false;
    }

    // Test resetting during an active transmission
    uart.rst = 1;
    clock_cycle(uart);
    uart.rst = 0;

    // Begin transmitting 0x55
    uart.data_in = 0x55;
    uart.tx_start = 1;
    clock_cycle(uart);
    uart.tx_start = 0;

    // Enter START state
    clock_cycle(uart);

    // Advance partway through the transmission
    for (int i = 0; i < 15; i++) {
        clock_cycle(uart);
    }

    // Check that transmission is still active
    bool was_busy = (uart.busy == 1);

    // Reset in the middle of transmission
    uart.rst = 1;
    clock_cycle(uart);

    // Check the reset outputs
    bool reset_passed = was_busy &&
                        (uart.tx == 1) &&
                        (uart.busy == 0);

    uart.rst = 0;

    // Verify another transmission can start after reset
    bool recovery_passed = test_frame(uart, 0x41, false);

    if (reset_passed && recovery_passed) {
        std::cout << "Mid-transmission reset test PASSED!"
                << std::endl;
    }
    else {
        std::cout << "Mid-transmission reset test FAILED!"
                << std::endl;
        all_tests_passed = false;
    }

    vcd.close();

    return all_tests_passed ? 0 : 1;
}